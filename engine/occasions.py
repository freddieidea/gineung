def types_here(upjong, lid=None):
    """이 업종·기능에서 이름으로 따로 가르는 종류"""
    out = set()
    for t, _, _, ups, _ in SPECIAL:
        if str(upjong) in ups:
            pre = ups[str(upjong)]
            if pre is None or (lid and str(lid).startswith(pre)): out.add(t)
    return out
