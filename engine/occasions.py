# 업종 이름에 공백이 섞여 있어 낱말로 자르지 않고, 알려진 업종 목록과 맞춰 나눔
def _split(s, known):
    out = set(); rest = " " + s + " "
    for u in sorted(known, key=len, reverse=True):
        if f" {u} " in rest: out.add(u); rest = rest.replace(f" {u} ", " ")
    return out, rest.strip()
