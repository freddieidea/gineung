def wanted_types(*texts):
    t = " ".join(str(x or "") for x in texts)
    return {k for k, _, say, _, _ in SPECIAL if re.search(say, t, re.I)}
def wanted_for(user_text, closed_name="", want=""):
    """주민이 원하는 좁은 종류: 지금 한 말이 먼저. '일반 카페로'라고 하면 문 닫은 곳이 라이브카페여도 일반 카페로"""
    u = str(user_text or "")
    if re.search(r"(일반|그냥|보통|평범한|다른)\s?(카페|미용실|술집|세탁소)|커피\s?(마시|한잔)", u) or ("카페" in u and not wanted_types(u) and not re.search(r"비슷|같은|그런|대신|이어", u)):
        return wanted_types(u, want)   # '카페에서 공부하고 싶어요'처럼 주민이 그냥 카페를 말하면 문 닫은 곳(스터디카페)의 종류를 따르지 않음
    closed_t = {k for k, rx, _, _, _ in SPECIAL if closed_name and re.search(rx, str(closed_name), re.I)}   # 문 닫은 곳은 가게 이름으로
    return wanted_types(user_text, want) | closed_t
_SOFT = {t for t, *_, soft in SPECIAL if soft}
_OPEN = {"운동화 세탁"}
_MIXED = {"기타 오락장", "기타 스포츠시설 운영업"}
def special_check(upjong, name, wanted, lid=None):
    """(보여 줄지, 뒤로 미는 분) — 따로 가르는 종류는 그 종류를 원할 때만, 그 종류를 원하면 같은 종류만"""
    ts = types_here(upjong, lid)
    if not ts: return True, 0
    t = special_type(upjong, name, lid); w = wanted & ts
    if w & _OPEN: return True, 0   # 운동화 세탁을 찾으면 일반 세탁소(크린토피아 등)도 함께 (바람 판단이 가름)
    if w: return (t in w), 0
    if t is None or str(upjong) in _MIXED: return True, 0   # 기타 오락장은 원래 여러 가지가 섞인 업종이라, 좁은 종류를 원할 때만 가름 (아이와 놀 곳을 찾으면 키즈카페도 나와야 함)
    return (True, 6) if t in _SOFT else (False, 0)
def types_for_leaf(lid):
    """이 기능에서 이름으로 가르는 세부 종류 전부 (업종을 가리지 않음)"""
    return {t for t, _, _, ups, _ in SPECIAL for pre in ups.values() if pre is None or (lid and str(lid).startswith(pre))}
def name_is(types, name):
    return any(re.search(rx, str(name or ""), re.I) for t, rx, _, _, _ in SPECIAL if t in types)
