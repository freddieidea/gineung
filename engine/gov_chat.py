def _dong_ok(dn, q):
    """행정동 맞추기: '상인동' → 상인1동·상인2동·상인3동, '범어1동' → 범어1동만, '불로동' → 불로·봉무동"""
    if not q: return True
    d = re.sub(r"\s", "", str(dn or "")); qq = re.sub(r"\s", "", str(q))
    ar = _area(q)
    if ar is not None: return d in ar
    qq = re.sub(r"(지역|지구|일대|쪽|생활권)$", "", qq) or qq   # '안심 지역' → 안심1·2·3·4동
    if not d: return False
    if d == qq: return True
    m_ = re.fullmatch(r"(.+?)(\d)동", qq)
    if m_ and re.fullmatch(re.escape(m_[1]) + r"[\d·,]*" + m_[2] + r"[\d·,]*동", d): return True   # '신천2동' → 신천1·2동, '두류2동' → 두류1,2동
