def _norm(v):
    """숫자 비교용: 1,000 → 1000 / 0.90 → 0.9 / 007 → 7"""
    v = str(v).replace(",", "")
    if "." in v: v = v.rstrip("0").rstrip(".")
    return v.lstrip("0") or "0" if "." not in v else (("0" + v) if v.startswith(".") else v)
def _qs(d):
    import urllib.parse
    return urllib.parse.urlencode({k: v for k, v in d.items() if v not in (None, "")})
