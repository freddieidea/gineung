    stem = re.sub(r"(동|읍|면)$", "", qq)
    if not stem: return False
    if re.fullmatch(re.escape(stem) + r"[\d.·]*(가)?(동|읍|면)", d): return True
    return any(p_ == stem or re.fullmatch(re.escape(stem) + r"[\d.]*(가)?동", p_) for p_ in d.split("·"))
