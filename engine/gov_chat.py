    def _trim_meta(self, out):
        """답 글에서 에이전트의 속사정만 말하는 문장을 뺌 (10/22 헌준님: 담당자에게 처리 과정을 하나하나 보고할 필요 없음). 결론 문장이 남을 때만"""
        try:
            said = out.get("_said") or ""
            sents = [x for x in re.split(r"(?<=[.!?])\s+|\n", said) if x.strip()]
            keep = [x for x in sents if not any(re.search(p_, x) for p_ in self.META)]
            nums = lambda t: set(re.findall(r"\d[\d,]*", t))
            shown = [x for x in keep if re.search(r"(지도|화면)(에|으로)[^.]{0,30}(표시했|띄웠|찍었|보여 드렸)", x)]
            for x in shown:   # '25곳을 지도에 표시했습니다' — 같은 숫자를 다른 문장이 이미 말하면 뺌
                others = " ".join(y for y in keep if y is not x)
                if others and nums(x) <= nums(others): keep = [y for y in keep if y is not x]
            if keep and len(keep) < len(sents):
                rest = [b_ for b_ in out["blocks"] if isinstance(b_, dict) and set(b_) != {"text"}]
                out["_said"] = " ".join(keep); out["blocks"] = [{"text": " ".join(keep)}] + rest
        except Exception: pass

    def _note(self, blocks):
        """이번 답에서 보여 드린 자료를 한 줄로 (다음 말의 '여기·이 시설들'을 알아듣게)"""
        out = []
        for b_ in blocks:
            k = b_.get("kind")
            if k == "list": out.append(f"{b_['title']}: " + ", ".join(f"{r.get('상호')}({' '.join(x for x in (r.get('구군'), r.get('행정동')) if x)}, {r.get('구분')})" for r in b_["rows"][:8]))
            elif k == "zones": out.append(f"{b_['title']}: " + ", ".join(f"{r.get('구군')} {r.get('행정동')} {r.get('시설')}(주민 {r.get('주민')})" for r in b_["rows"][:8]))
            elif k == "card": out.append(f"시설 카드: {b_['row'].get('상호')}({b_.get('label')})")
            elif k == "policy": out.append(f"{b_['fn']} 입지 후보({b_['data'].get('구군') or '대구 전체'}): " + ", ".join(f"{c['구군']} {c['행정동']}" for c in b_["data"]["후보"]))
            elif k == "effect": out.append(f"{b_['fn']} 개설 효과: {b_['data'].get('구군')} {b_['data'].get('행정동')}")
            elif k == "table": out.append(f"표: {b_.get('title')}")
            elif k == "doc": out.append(f"문서: {b_.get('title')}")
            elif k == "action": out.append(f"확인 카드: {b_.get('title')} · {b_.get('target')}")
        return " / ".join(out)[:700]

    def _check(self, st, body, ctx):
        if not body.strip(): return "empty"
        sents = [x.strip() for x in re.split(r"(?<=[.!?])\s+|\n", body) if x.strip()]
        if any(re.search(r"(임|함|됨|음|없음|있음)[.。]?$", x) and len(x) > 12 for x in sents): return "style"   # 대화는 경어체 (명사형 종결 금지)
        if re.search(r"</?(answer|parameter|invoke|function_calls)\b", body): return "format"
        if not re.search(r"[.!?。)\]다요]\s*$", body.strip()): return "cut"   # 답이 중간에 끊김 (긴 문서와 답을 한꺼번에 쓰다 길이 한도에 걸린 경우)
        carded = "propose_action" in (st.get("used_now") or [])
        if not st.get("screen_done") and any(DONE_CLAIM.search(x) and not COND.search(x) and not STATE_DESC.search(x) and not (carded and re.search(r"카드|메모", x)) for x in re.split(r"(?<=[.다음함됨임])\s+|\n|/", body)): return "claim"   # 반영은 담당자가 카드를 눌러야 됨
        if any(re.search(r"(요약|문서|보고서|엑셀|PDF|정리본|메모|문안|한 장|보고용)[^.]{0,30}(만들었|정리했|작성했|준비했|담았|만들어 ?(두었|드렸|놓았)|정리해 ?(두었|드렸))", x) and not re.search(r"않|못|없|드릴까요", x)
               for x in re.split(r"(?<=[.!?])\s+", body)) and not ({"make_document"} & set(st.get("used_now") or [])): return "doc_claim"   # 문서를 만들었다면서 만들지 않음
        if re.search(r"(?<![A-Za-z_])(area_overview|report_overview|search_facilities|facility_detail|gap_areas|resident_signals|pre_review|policy_candidates|open_effect|criteria|show_on_screen|propose_action|make_document)(?![A-Za-z_])", body): return "tool_name"   # 내부 도구 이름은 담당자에게 보이지 않게
        if CARD_SHOWN.search(body) and "propose_action" not in (st.get("used_now") or []): return "card_claim"   # 카드를 띄웠다면서 띄우지 않음
        allowed = set(); c2 = ctx.replace(",", "")
        for m in re.finditer(r"\d+(?:\.\d+)?", c2):
            v = m.group(0); allowed.add(_norm(v))
            try:
                f = float(v)
                if f >= 100: allowed.update({_norm(f"{f / 1000:.1f}"), _norm(f"{f / 1000:.2f}"), str(int(round(f / 1000)))})
                if f != int(f): allowed.add(str(int(round(f))))
                if f < 1 and f > 0: allowed.add(str(int(round(f * 100))))
                if 1 <= f <= 1440 and ("분" in ctx): allowed.add(str(int(round(f))))
            except ValueError: pass
        b2 = body.replace(",", "")
        for m in re.finditer(r"\d+(?:\.\d+)?", b2):
            v = m.group(0); tail = b2[m.end():m.end() + 3]
            if re.match(r"\s*(월|일|시|년|차|순위|번째|위\b|가지|단계)", tail): continue
            if _norm(v) not in allowed: return "num:" + v
        toks = re.findall(r"[가-힣A-Za-z0-9&]+", body); cx = re.sub(r"\s", "", ctx); N = self.names()
        for n in range(1, 4):
            for i in range(len(toks) - n + 1):
                w = "".join(toks[i:i + n])
                if len(w) >= 4 and w in N and w not in cx and not re.search(r"(보건소|구청|군청|교육지원청|교육청|행정복지센터|우체국|시청)$", w) and FAC_SUFFIX.search(w): return "name:" + w   # 시설 이름처럼 끝나는 말만 (10/25: '동네에서' 같은 가게 이름이 일반 낱말과 겹쳐 잘못 걸림)
        said = re.sub(r"\s", "", str(st.get("_utter") or ""))
        for t_ in JARGON:   # 서비스 용어를 뜻풀이 없이 쓰면 (담당자가 먼저 쓴 말이면 괜찮음)
            m_ = re.search(t_, body)
            if m_ and re.sub(r"\s", "", m_.group(0)) not in said and not re.match(r"\s*\(|['’\"”」]", body[m_.end():m_.end() + 3]): return "jargon:" + m_.group(0)   # 따옴표로 짚어 뜻을 설명하는 경우는 괜찮음
        return None

