    def _catalog(self):
        rows = []
        for c in self.E.T["categories"]:
            for p in c["purposes"]:
                for l in p["leaves"]:
                    ks = [k for (L, k) in self.E.kind if L == l["id"]]
                    el = [f"{k}({self.E.kind[(l['id'], k)]['elig']})" for k in ks if self.E.kind[(l['id'], k)].get("elig") not in (None, "None", "")]
                    rows.append(f"{l['id']} {l['name']}: {l['desc']}" + (f" (예: {l['examples']})" if l.get("examples") else "")
                                + (f" | 종류: {', '.join(ks)}" if ks else "") + (f" | 자격 필요: {', '.join(el)}" if el else ""))
        from conversation import SERVICES
        svc = "\n".join(f"{sid}: {v['이름']} — {v['하는일']}" for sid, v in SERVICES.items())
        return "\n".join(rows) + "\n\n[생활 서비스 (service_info의 service_id)]\n" + svc

