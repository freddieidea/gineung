    def _call(self, model, tools, msgs, emit):
        if not emit: return self.client.messages.create(model=model, max_tokens=1200, system=self.system, tools=tools, messages=msgs)
        blocks = {}; flow = Flow(emit, getattr(self, "_said", ""))
        with self.client.messages.stream(model=model, max_tokens=1200, system=self.system, tools=tools, messages=msgs) as s:
            for ev in s:
                t = getattr(ev, "type", "")
                if t == "content_block_start":
                    cb = ev.content_block; ct = getattr(cb, "type", "")
                    if ct == "tool_use":
                        blocks[ev.index] = {"name": cb.name, "json": ""}
                        if cb.name in STATUS: emit("status", STATUS[cb.name])
                    elif ct == "server_tool_use": emit("status", STATUS["web_search"])
                elif t == "content_block_delta" and getattr(ev.delta, "type", "") == "input_json_delta":
                    b = blocks.get(ev.index)
                    if b is not None:
                        b["json"] += ev.delta.partial_json
                        if b["name"] == "answer": flow.feed(partial_text(b["json"]))
            for b in blocks.values():
                if b["name"] == "answer": flow.feed(partial_text(b["json"]), final=True)   # 마지막 문장까지
            return s.get_final_message()

