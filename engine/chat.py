    def start(self, lon, lat, gu=None, closed_fid=None, origin_name=None, origin_closed=False, origin_kind=None):
        st = self.C.start(lon, lat, gu=gu, closed_fid=closed_fid)
        st.update(stage="chat", msgs=[], turns=0, shown_names=set(), origin_closed=origin_closed)
        if origin_name: st["origin_name"] = origin_name
        st["origin_kind"] = origin_kind or ("문 닫은 곳" if closed_fid else None)
        if closed_fid:
            r = self.E.F.loc[closed_fid]; st["shown_names"].add(re.sub(r"\s", "", str(r["상호"])))
            pair = st.pop("confirm_pair", None); st.pop("opening_options", None)
            spec = self._ask_spec(st, closed_fid)
            if spec: return st, ("agent", {"leaf": spec["first"]["leaf"], "kind": spec["first"]["kind"], "brief": self._brief(closed_fid, spec)})   # 첫 마디는 에이전트가 스스로 판단 (화면은 스트리밍으로 받음)
            return st, ("agent", {})
        return st, {"type": "question", "text": "어떤 곳을 찾으세요?", "blocks": [{"text": "어떤 곳을 찾으세요?"}],
                    "options": ["미용실 찾아요", "가까운 병원", "장 볼 곳", "경로당·복지관"], "기준": self._origin_label(st)}

    def _ask_spec(self, st, fid):
        """문 닫은 시설을 눌렀을 때 여쭐 것 — 그 시설이 하던 일(기능 자료)에서 나옴 (헌준님 지적 10/16: 시설 유형에 맞는 맥락·의도)
         1) 무엇을 하러 가셨는지: 하던 일이 둘 이상이면 그 일들이 보기 (편의점: 먹거리·생활용품·도시락·택배·현금…)
         2) 누구랑: 고른 일이 함께 머무는 곳(식당·카페·노래방 등)일 때만 나타남
         3) 언제: 고른 일이 약국·병의원처럼 여는 시간이 중요할 때만
         4) 어떻게 가실지: 매주 가는 동네 가게(편의점·슈퍼·식당·미용실 등)는 묻지 않고 걸어서 (버스 버튼은 결과에 있음). 가끔 가는 곳·공공시설만 여쭘"""
        fs = [f for f in self.E.functions_of(fid) if f["role"] == "주" and f["confidence"] in ("높음", "보통")]
        fs += [f for f in self.E.functions_of(fid) if f["role"] == "부" and f["confidence"] in ("높음", "보통")]
        def members(lid, kd):   # 그 일에서 이 종류와 함께 찾는 종류들 (같으면 결과가 같은 일)
            v = self.E.kind.get((lid, kd)) if kd else None
            return frozenset(k for (L, k), w in self.E.kind.items() if L == lid and v and w["group"] == v["group"]) if v else None
        seen = set(); groups_seen = set(); opts = []
        main_social = any(f["leaf"] in SOCIAL for f in fs if f["role"] == "주")
        for f in fs:
            if f["leaf"] in seen or f["leaf"] not in self.E.leaf: continue
            seen.add(f["leaf"]); L = self.E.leaf[f["leaf"]]
            kd = f.get("kind") if f.get("kind") not in (None, "None", "") else None
            if f["leaf"] == "P11.1.03" and main_social: continue   # 카페·노래방의 '친목 장소'는 '누구랑'으로 여쭘
            m = members(f["leaf"], kd)
            if m and m in groups_seen and f["leaf"] != "P01.1.06": continue   # 배달·포장은 가게는 같아도 하는 일이 달라 따로   # 결과가 같은 일은 하나로 (헬스장: '운동 시설'과 '운동·체력 관리')
            if m: groups_seen.add(m)
            name = re.sub(r"\s*(구입|이용)$", "", L["name"]); d = L.get("desc", "")
            sub = d if len(d) <= 14 and not any(w in d for w in re.findall(r"[가-힣]{2,}", name)) else ""   # 설명이 이름을 되풀이하면 뺌
            opts.append({"leaf": f["leaf"], "kind": kd, "보기": name, "설명": sub})
        if not opts: return None
        opts = opts[:6]; f0 = opts[0]
        first = {"leaf": f0["leaf"], "kind": f0["kind"], "others": []}
        groups = []
        if len(opts) > 1:
            groups.append({"key": "purpose", "말": "무엇을 하러 가셨어요?", "보기": [o["보기"] for o in opts], "설명": [o["설명"] for o in opts]})
