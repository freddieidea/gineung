    def _near_same(self, fid, within=700):
        """문 닫은 곳 가까이(곧은 거리 700m, 걸어서 10분쯤)에 같은 업종 가게가 있는지. 있으면 이동 방법을 묻지 않고 걸어서 찾음"""
        import numpy as np
        F = self.E.F; up = F.loc[fid, "업종"]
        if not hasattr(self, "_same_cache"): self._same_cache = {}
        if up not in self._same_cache:
            X = F[(F["업종"] == up) & (F["대안후보"] == "예") & F["경도"].notna()]
            self._same_cache[up] = (X.index.values, X["경도"].astype(float).values, X["위도"].astype(float).values)
        ids, lo, la = self._same_cache[up]
        try: x, y = float(F.loc[fid, "경도"]), float(F.loc[fid, "위도"])
        except Exception: return False
        d = np.hypot((lo - x) * 90300, (la - y) * 110540); d[ids == fid] = 1e9
        return bool((d <= within).any())

