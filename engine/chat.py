def partial_text(js):
    """answer 도구 입력(JSON 조각)에서 지금까지 들어온 text 값을 꺼냄"""
    m = re.search(r'"text"\s*:\s*"', js)
    if not m: return ""
    i = m.end(); out = []
    while i < len(js):
        ch = js[i]
        if ch == '"': break
        if ch == "\\":
            if i + 1 >= len(js): break
            nx = js[i + 1]
            if nx == "u":
                if i + 6 > len(js): break
                try: out.append(chr(int(js[i + 2:i + 6], 16)))
                except ValueError: pass
                i += 6; continue
            out.append({"n": "\n", "t": " ", '"': '"', "\\": "\\", "/": "/"}.get(nx, nx)); i += 2; continue
        out.append(ch); i += 1
    return "".join(out)
