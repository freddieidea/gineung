def for_item(funcs, ctx):
    """문 닫은 곳 하나에 맞는 일 (법정 확인 먼저). funcs: [{'기능','세부종류'}], ctx: {'gap','elder','far'} 참·거짓"""
    out = []; seen = set()
    lids = {(f["기능"], f.get("세부종류")) for f in funcs}
    for p in PROGRAMS:
        if p["id"] in seen: continue
        when = p["언제"]
        if when != "closed" and not ctx.get(when): continue
        if p["기능"] is not None:
            hit = False
            for lid, k in lids:
                if lid not in p["기능"]: continue
                ks = (p.get("kinds") or {}).get(lid)
                if ks and k not in ks: continue
                hit = True
            if not hit: continue
        seen.add(p["id"]); out.append({k: p[k] for k in ("id", "종류", "할일", "근거", "담당", "맞는상황") if k in p})
    out.sort(key=lambda x: {"법정 확인": 0, "지자체 사업": 1, "기관 협의": 2}.get(x["종류"], 3))   # 구·군이 직접 할 수 있는 일 먼저
    return out
