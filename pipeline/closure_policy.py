def group(upjong, source=""):
    u = str(upjong or "")
    if source == "공공" or u in PUBLIC: return "공공·복지"
    if OCCASIONAL.search(u): return "가끔 가는 곳"
    return "일상 가게"
def _d(s):
    try: return datetime.date.fromisoformat(str(s)[:10])
    except Exception: return None
def window(upjong, closed_on, updated_on=None, source="", today=None, extend_until=None):
    """돌려줌: {묶음, 시작일, 지도표시까지, 안내까지, 단계('지도 표시'|'안내만'|'지남')}. 폐업일을 모르면 None"""
    c = _d(closed_on)
    if not c: return None
    today = today or datetime.date.today()
    start = c; u = _d(updated_on)
    if u and c < u <= c + datetime.timedelta(days=90): start = u
    g = group(upjong, source); md, ad, _ = GROUPS[g]
    map_until = start + datetime.timedelta(days=md); ad_until = start + datetime.timedelta(days=ad)
    e = _d(extend_until)
    if g == "공공·복지" and e and e > ad_until: ad_until = e; map_until = max(map_until, e)
    stage = "지도 표시" if today <= map_until else ("안내만" if today <= ad_until else "지남")
    if c > today: stage = "폐업 예정"   # (10/29) 폐업일이 앞으로인 신고(예정): 그날 전까지는 지도에 '문 닫음'을 띄우지 않음
    return {"묶음": g, "시작일": start.isoformat(), "지도표시까지": map_until.isoformat(), "안내까지": ad_until.isoformat(), "단계": stage}

