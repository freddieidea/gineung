def sport_type(name):
    n = re.sub(r"\s+", " ", str(name)).strip()
    if n in EXCLUDE: return "제외", EXCLUDE[n]
    if n in FIX: return FIX[n], ""
    hit = [t for p, t in RULES if re.search(p, n)]
    if not hit: raise ValueError(f"종목을 알 수 없는 공공체육시설: {n}")
    return hit[0], ""
