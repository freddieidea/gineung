# 헌준님이 대화에서 직접 판단해 준 예시를 판단 모델의 첫 사례로 넣음 (10/19)
#  예시를 규칙으로 쓰지 않고 '사례'로 넣어, 모델이 특징(도심·생명 직결·규모·자료 확실성…)으로 일반화해서 배우게 함
#  이미 넣은 예시는 다시 넣지 않음. 쓰는 법: python pipeline/seed_examples.py
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, os.path.join(ROOT, "engine"))
from gov_agent import GovAgent
import gap_agent as GA
EX = [  # (fid, 판단, 헌준님 말씀)
    ("S:MA010120220812263134", "관찰", "도시에서 약국까지 몇 분 더 걷는 건 위험하지 않음 (진천동 약국, 18분 거리에 다른 약국)"),
    ("S:MA010120220808875853", "관찰", "도심 약국이 사라진 것을 심각으로 보고한 것은 오류 (지산1동 아나약국)"),
    ("S:MA010120220812137868", "해당 없음", "호텔 안 미용실은 주민이 쓰던 곳이 아님 (팔공산호텔컷트)"),
    ("S:MA0101202409A0020395", "해당 없음", "근처에 다른 마트가 있음 (동구 엘지마트각산점)"),
    ("S:MA010120220808834511", "보고", "농촌 마을의 마지막 식료품점이 사라지면 생활 기능 자체가 사라짐 (의흥면 파전구판장, 제안자 답변서)"),
    ("P:전통시장:의흥시장", "보고", "시골에서 시장은 도심과 중요도가 아예 다름 (군위 의흥시장)"),
    ("S:MA010120220808920031", "보고", "동네 반경 5km 안에 응급실이 있던 병원이 문을 닫으면 심각 (천주성삼병원)"),
    ("S:MA010120220808919480", "보고", "임산부가 출산하지 못하거나 위급한 신생아를 받을 곳이 없는 수준은 도심이라도 보고 (대구파티마병원)"),
]
G = GovAgent(); have = {(r["fid"], r["누가"]) for r in GA.precedents()}
n = 0
for fid, label, why in EX:
    if (fid, "헌준님 예시") in have: continue
    if G._remember(fid, label, why, "헌준님 예시"): n += 1
    else: print("재어 볼 공백이 없어 넣지 못함:", fid)
print("넣은 예시", n, "| 다시 배움:", G.train())
